#!/bin/sh -e
# GPU integration test for the per-profile ungapped p-value filter (manual).
#
# Runs `ungappedprefilter` on the GPU and compares its output (hit set and
# scores, via createtsv) against the CPU prefilter, both with the p-value gate
# on (--ungapped-pvalue 0.05) and with it off (1.0, which exposes the full
# ungapped score vector, not just the gated subset).
#
# The GPU output (hit set + scores) must equal the CPU output exactly. In rare
# cases the UInt8x4 kernel can under-report scores (byte saturation, see README
# limitation 3) and a strict mismatch may then be a kernel limitation rather
# than a regression; this test does not special-case that.
# On a Blackwell device the native binary selects the UInt8x4 kernel; binaries
# built with -DMARV_FORCE_GAPLESS_CC_MAJOR=<arch> select another architecture's
# config set (Turing/Ampere/...) and are compared the same way. The
# int8+legacy stress build (-DMARV_FORCE_INT8=1 with a legacy arch) covers the
# datatype/bias-shift mismatch. See README "Testing other GPU kernel families".
#
# Fixtures are generated by gen_tiny_profile_fixtures.py.
#
# Usage:
#   MMSEQS_BIN=/path/to/mmseqs sh src/test/TestTinyProfileGpuFilter.sh
# Optional:
#   MMSEQS_FORCED_BINS="turing:/path/mmseqs ampere:/path/mmseqs"
# If unset, build-turing/src/mmseqs, build-ampere/src/mmseqs and
# build-stress/src/mmseqs are used when present.
FAIL=0
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
if [ -n "$MMSEQS_BIN" ]; then MMSEQS="$MMSEQS_BIN"; fi
if [ -z "$MMSEQS" ]; then
  if [ -x "$ROOT/build-cuda/src/mmseqs" ]; then MMSEQS="$ROOT/build-cuda/src/mmseqs"; fi
fi
if [ -z "$MMSEQS" ]; then MMSEQS="mmseqs"; fi
echo "MMSEQS=$MMSEQS"
command -v "$MMSEQS" >/dev/null 2>&1 || { echo "SKIP: mmseqs binary not found"; exit 0; }
if ! command -v nvidia-smi >/dev/null 2>&1; then echo "SKIP: no nvidia-smi"; exit 0; fi
if ! nvidia-smi -L >/dev/null 2>&1; then echo "SKIP: no GPU device"; exit 0; fi

if [ -z "$MMSEQS_FORCED_BINS" ]; then
  MMSEQS_FORCED_BINS=""
  for d in turing ampere stress; do
    if [ -x "$ROOT/build-$d/src/mmseqs" ]; then MMSEQS_FORCED_BINS="$MMSEQS_FORCED_BINS $d:$ROOT/build-$d/src/mmseqs"; fi
  done
fi

T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT INT TERM
TD="$ROOT/src/test"
"$MMSEQS" convertmsa "$TD/tiny_mix.sto" "$T/mix.msa" --identifier-field 0 >/dev/null
"$MMSEQS" msa2profile "$T/mix.msa" "$T/mix.prof" --threads 1 >/dev/null
"$MMSEQS" createdb "$TD/tiny_target.fasta" "$T/targetDB" --threads 1 >/dev/null
"$MMSEQS" makepaddedseqdb "$T/targetDB" "$T/targetDB_pad" >/dev/null

# CPU reference prefilters: gated (p=0.05) and gate-off (p=1.0, full scores).
cpu_pref() { # $1=tag $2=pvalue
  "$MMSEQS" ungappedprefilter "$T/mix.prof" "$T/targetDB" "$T/prefCPU_$1" \
    --prefilter-mode 1 --ungapped-pvalue "$2" --gpu 0 --threads 1 >/dev/null
  "$MMSEQS" createtsv "$T/mix.prof" "$T/targetDB" "$T/prefCPU_$1" "$T/prefCPU_$1.tsv" >/dev/null
  sort "$T/prefCPU_$1.tsv" > "$T/prefCPU_$1.sorted"
}
cpu_pref p05 0.05
cpu_pref p10 1.0
echo "CPU prefilter p=0.05: $(wc -l < "$T/prefCPU_p05.tsv") hits; p=1.0: $(wc -l < "$T/prefCPU_p10.tsv") hits"

run_pref() { # $1=binary $2=tag $3=pvalue
  "$1" ungappedprefilter "$T/mix.prof" "$T/targetDB_pad" "$T/pref_$2" \
    --prefilter-mode 1 --ungapped-pvalue "$3" --gpu 1 --threads 1 >/dev/null 2>"$T/$2.err" || return 1
  "$1" createtsv "$T/mix.prof" "$T/targetDB_pad" "$T/pref_$2" "$T/pref_$2.tsv" >/dev/null || return 1
  sort "$T/pref_$2.tsv" > "$T/pref_$2.sorted"
  return 0
}

compare() { # $1=cpu ref $2=got $3=label
  if diff -q "$1" "$2" >/dev/null; then
    echo "ok: $3 == CPU (hit set + scores)"
  else
    echo "FAIL: $3 != CPU (hit set + scores)"
    diff "$1" "$2" | head -10
    FAIL=1
  fi
}

# Native binary: determinism + CPU parity, gate on and gate off.
if run_pref "$MMSEQS" native1 0.05; then
  run_pref "$MMSEQS" native2 0.05 || { echo "FAIL: native second run"; FAIL=1; }
  if diff -q "$T/pref_native1.sorted" "$T/pref_native2.sorted" >/dev/null; then
    echo "ok: native GPU determinism"
  else echo "FAIL: native GPU nondeterministic"; FAIL=1; fi
  compare "$T/prefCPU_p05.sorted" "$T/pref_native1.sorted" "native (p=0.05)"
else
  echo "FAIL: native GPU prefilter failed:"; head -5 "$T/native1.err" 2>/dev/null; FAIL=1
fi
if run_pref "$MMSEQS" native10 1.0; then
  compare "$T/prefCPU_p10.sorted" "$T/pref_native10.sorted" "native (p=1.0 full scores)"
else
  echo "FAIL: native GPU p=1.0 prefilter failed:"; head -5 "$T/native10.err" 2>/dev/null; FAIL=1
fi

# Forced-arch binaries (Turing/Ampere config sets, int8+legacy stress).
for ENTRY in $MMSEQS_FORCED_BINS; do
  NAME=${ENTRY%%:*}
  BIN=${ENTRY#*:}
  if run_pref "$BIN" "$NAME" 0.05; then
    compare "$T/prefCPU_p05.sorted" "$T/pref_$NAME.sorted" "$NAME (p=0.05)"
  else
    echo "FAIL: $NAME GPU prefilter failed:"; head -5 "$T/$NAME.err" 2>/dev/null; FAIL=1
  fi
  if run_pref "$BIN" "${NAME}_full" 1.0; then
    compare "$T/prefCPU_p10.sorted" "$T/pref_${NAME}_full.sorted" "$NAME (p=1.0 full scores)"
  else
    echo "FAIL: $NAME GPU p=1.0 prefilter failed:"; head -5 "$T/${NAME}_full.err" 2>/dev/null; FAIL=1
  fi
done

# mode 3 must hard-error
if "$MMSEQS" ungappedprefilter "$T/mix.prof" "$T/targetDB_pad" "$T/prefX" --prefilter-mode 3 --gpu 1 --threads 1 >/dev/null 2>&1; then
  echo "FAIL: --prefilter-mode 3 did not error"; FAIL=1
else echo "ok: --prefilter-mode 3 hard-errors"; fi

if [ "$FAIL" = "0" ]; then echo "ALL GPU FILTER TESTS PASSED"; else echo "FAILURES"; exit 1; fi
